#!/bin/bash
# Refresh desktop/js/craft-launcher-release.js from the latest ArtCraft Launcher release
# at github.com/storytold/craft-launcher, so the "Launcher for Mac/Windows/Linux" buttons
# link straight to the installer file for the visitor's OS (as getartcraft.com/download does).
#
# Usage: ./install/refresh-launcher.sh        (run from desktop/ or desktop/install/)

set -euo pipefail

REPO="storytold/craft-launcher"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$SCRIPT_DIR/../js/craft-launcher-release.js"

JSON="$(curl -fsSL -H "Accept: application/vnd.github+json" "https://api.github.com/repos/$REPO/releases/latest")"

printf '%s' "$JSON" | python3 -I -c '
import json, sys
rel = json.load(sys.stdin)
skip = (".asc", ".sig", ".zsync", ".json", ".txt")
assets = sorted(a["name"] for a in rel.get("assets", []) if not a["name"].endswith(skip))
if not assets:
    sys.exit("No release assets found")
tag = rel["tag_name"]
data = {"repo": sys.argv[1], "tag": tag, "version": tag.lstrip("v"), "assets": assets}
with open(sys.argv[2], "w") as f:
    f.write("// Generated by desktop/install/refresh-launcher.sh from the latest github.com/" + sys.argv[1] + " release. Do not edit by hand.\n")
    f.write("var craftLauncherRelease = " + json.dumps(data, indent=2) + ";\n")
print("Wrote " + sys.argv[2] + " for " + tag + " (" + str(len(assets)) + " files)")
' "$REPO" "$OUT"
